// Regenerates components/logoArt.ts from the colour logo SVGs in public/brand/ (run after updating the brand kit):
//   node scripts/logo-art.mjs
// The ink cells and wordmark get class "logo-ink" (filled by the scheme's --logo-ink); the door keeps the logo green.
import { readFileSync, writeFileSync } from "node:fs";

const VARIANTS = { mark: "domata-mark.svg", horizontal: "domata-lockup-horizontal.svg", stacked: "domata-lockup-stacked.svg" };
const INK = 'fill="#26262B"';
const DOOR = 'fill="#0F9246"';

const art = {};
for (const [variant, file] of Object.entries(VARIANTS)) {
  const svg = readFileSync(new URL(`../public/brand/${file}`, import.meta.url), "utf8");
  const [, viewBox] = svg.match(/viewBox="([^"]+)"/);
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[\s\S]*?<\/title>/, "");
  if (!inner.includes(INK) || inner.split(DOOR).length !== 2) throw new Error(`${file}: expected ink cells and one door`);
  art[variant] = { viewBox, inner: inner.replaceAll(INK, 'class="logo-ink"') };
}

writeFileSync(
  new URL("../components/logoArt.ts", import.meta.url),
  `// Generated by scripts/logo-art.mjs from public/brand/ (the colour logo SVGs). Don't edit by hand.\n\nexport const LOGO_ART = ${JSON.stringify(art, null, 2)} as const;\n`,
);
